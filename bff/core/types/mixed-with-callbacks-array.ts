/****
 * Массив, содержащий значения типа T или функции, возвращающие значения типа T, массив T или undefined.
 *
 * Используется, когда элементы массива могут быть либо статичными значениями,
 * либо вычисляемыми динамически при помощи функций.
 *
 * @template T Тип элементов массива.
 */
export type MixedWithCallbacksArray<T> = (T | (() => T | T[] | undefined))[];
